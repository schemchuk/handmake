import type { Show } from '../show';
import type { Post, PostType } from '../post';
import type { Collection, Work } from '../work';
import type { RemoteId } from './channel';

/**
 * Publish ledger (architecture section 3): per-channel delivery status of a
 * post, kept separate from the post so retries do not rewrite it. Pure
 * transition functions live in the ledger module (T06).
 */

export type ChannelStatus = 'pending' | 'done' | 'failed';

export interface LedgerEntry {
  status: ChannelStatus;
  remoteIds: RemoteId[];
  /** Last error message when status is "failed". */
  error?: string;
  /** ISO timestamp of the last transition. */
  updatedAt: string;
}

export interface PublishLedger {
  tenantId: string;
  postId: string;
  channels: Record<string, LedgerEntry>;
}

export interface PhotoFile {
  fileName: string;
  data: Uint8Array;
}

/**
 * Where published content lives. Git repo now; tenant repos or R2 later.
 * A post is in the store only after the author approved it and the publish
 * run saved it, so "in the store" means "published" (channel delivery
 * status is the ledger's business, not the site's).
 *
 * Photos are addressed by (tenantId, postId, fileName), where fileName is
 * one of `post.photos`; readers never see store paths (ADR 016). Works and
 * collections use typed methods with the same tenant isolation (T36a).
 */
export interface ContentStore {
  /** Approved works only; supplied photos must be declared. Foreign identity collisions fail. */
  saveWork(work: Work, photos: PhotoFile[]): Promise<void>;
  readWork(tenantId: string, workId: string): Promise<Work | undefined>;
  /** Newest first by instant, then id descending (compareNewestFirst). */
  listWorks(tenantId: string): Promise<Work[]>;
  readWorkPhoto(
    tenantId: string,
    workId: string,
    fileName: string,
  ): Promise<Uint8Array | undefined>;
  saveCollection(collection: Collection): Promise<void>;
  readCollection(tenantId: string, slug: string): Promise<Collection | undefined>;
  /** Configured order ascending, then slug ascending (compareCollections). */
  listCollections(tenantId: string): Promise<Collection[]>;
  savePost(post: Post, photos: PhotoFile[]): Promise<void>;
  readPost(tenantId: string, postId: string): Promise<Post | undefined>;
  /** All posts of a tenant, newest first (by `date`, then by id descending). */
  listPosts(tenantId: string): Promise<Post[]>;
  /** Bytes of one photo of a post; undefined if the post or the file is absent. */
  readPostPhoto(
    tenantId: string,
    postId: string,
    fileName: string,
  ): Promise<Uint8Array | undefined>;
  readLedger(tenantId: string, postId: string): Promise<PublishLedger | undefined>;
  writeLedger(ledger: PublishLedger): Promise<void>;
}

/** Read-only content capability for runtimes without filesystem access. */
export type CollectionReader = Pick<ContentStore, 'listCollections'>;

export type DraftState =
  'collecting' | 'translating' | 'ready' | 'publishing' | 'published' | 'failed';

/** What an approved draft becomes: a regular post, a work or a show. */
export type DraftKind = 'post' | 'work' | 'show';

export interface Draft {
  tenantId: string;
  draftId: string;
  state: DraftState;
  kind: DraftKind;
  /** Post type (free, announcement, reminder, wotw-poll, wotw-result). */
  type: PostType;
  /** Kind-specific extras as opaque JSON: poll spec, entry refs, collection. */
  extras: Record<string, unknown>;
  texts: Record<string, string>;
  /** Opaque photo references (Telegram file_ids), not binary data. */
  photoRefs: string[];
  createdAt: string;
  updatedAt: string;
}

/** Draft persistence for the bot. D1 now; the state machine is pure (T14).
 * The D1 implementation adds optimistic locking (a version counter quoted on
 * every write) and one-collecting-draft-per-chat enforcement on top of this
 * minimal port, because the Worker handles Telegram updates concurrently. */
export interface DraftStore {
  get(tenantId: string, draftId: string): Promise<Draft | undefined>;
  save(draft: Draft): Promise<void>;
  delete(tenantId: string, draftId: string): Promise<void>;
  listByState(tenantId: string, state: DraftState): Promise<Draft[]>;
}

/** Approved shows only. Originals remain in the linked work; generated bytes stay immutable. */
export interface ShowContentStore {
  saveShow(show: Show, media: PhotoFile[]): Promise<void>;
  readShow(tenantId: string, showId: string): Promise<Show | undefined>;
  listShows(tenantId: string): Promise<Show[]>;
  readShowMedia(
    tenantId: string,
    showId: string,
    fileName: string,
  ): Promise<Uint8Array | undefined>;
}
